const MONTHS: [string, string][] = [
  ['Ocak', 'January'],
  ['Şubat', 'February'],
  ['Mart', 'March'],
  ['Nisan', 'April'],
  ['Mayıs', 'May'],
  ['Haziran', 'June'],
  ['Temmuz', 'July'],
  ['Ağustos', 'August'],
  ['Eylül', 'September'],
  ['Ekim', 'October'],
  ['Kasım', 'November'],
  ['Aralık', 'December'],
];
const month = (tr: string) => MONTHS.find(([m]) => m === tr)?.[1] || tr;
const span = (s: string) =>
  s
    .replace(/(\d+)g (\d+)sa/, '$1d $2h')
    .replace(/(\d+)sa (\d+)dk/, '$1h $2m')
    .replace(/(\d+)sa$/, '$1h')
    .replace(/(\d+)g$/, '$1d')
    .replace(/(\d+) dk$/, '$1 min')
    .replace(/^şimdi$/, 'now');

